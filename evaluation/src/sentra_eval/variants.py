"""4.2: paraphrases of a question, proposed by a model and approved by a person.

The Vorlage asks for three styles — umgangssprachlich, fachsprachlich,
verkürzt — generated by an LLM to save time, then read by Hotline or WD before
they count, because "Freigegeben wird nur, was inhaltlich eindeutig dasselbe
meint". A variant that quietly asks a different question does not measure
robustness; it measures whether SENTRA answers two different questions the same
way, which is not a property anybody wants.

Generated by the **judge** model, not by CHAT_MODEL. Letting the system under
test write its own paraphrases would let it rephrase in whatever way it finds
easiest to answer, which is the opposite of a robustness check.

Frozen into the case version on approval, like the expected answer. Variants
that changed between rounds would make the rounds incomparable — and comparing
rounds is what 4.2 is for.
"""

import json
import logging
import re
from datetime import UTC, datetime
from uuid import UUID

from openai import OpenAI, OpenAIError
from sqlalchemy import select
from sqlalchemy.orm import Session

from sentra_eval.judge import JUDGE_MAX_TOKENS, JudgeUnavailable, judge_config
from sentra_eval.models import (
    FREIGEGEBEN,
    VARIANTEN_STILE,
    VORGESCHLAGEN,
    CaseVersion,
    Variant,
)

logger = logging.getLogger(__name__)

ERSTELLT_DURCH_LLM = "LLM (Erststellung)"

VARIANT_SYSTEM_PROMPT = """\
Du formulierst Fragen um, damit die Robustheit eines Auskunftssystems geprüft werden kann.

Zu einer gegebenen Frage erzeugst du drei Varianten, die inhaltlich exakt dasselbe erfragen:

- "umgangssprachlich": wie eine Person am Telefon fragen würde
- "fachsprachlich": mit der korrekten Fachterminologie
- "verkuerzt": stichwortartig, wie eine Suchanfrage

Die Varianten dürfen NICHT nach etwas anderem fragen, den Gegenstand nicht verengen \
und nicht erweitern. Keine Antworten, keine Erklärungen.

Antworte ausschließlich mit JSON:
{"umgangssprachlich": "...", "fachsprachlich": "...", "verkuerzt": "..."}\
"""


class VariantError(RuntimeError):
    """A variant operation the rules do not allow."""


class ApprovedVariantIsFrozen(VariantError):
    """An approved variant cannot be changed.

    The same rule the expected answer has, for the same reason: a round
    measured robustness against these words, and changing them afterwards makes
    the result unexplainable.
    """


def propose(session: Session, version: CaseVersion) -> list[Variant]:
    """Ask the judge model for three paraphrases. Stores them as proposals.

    Replaces any existing *proposals* for the version and leaves approved ones
    alone — regenerating is a normal thing to want when the first attempt was
    poor, and losing an approval to it would not be.
    """
    config = judge_config()
    client = OpenAI(base_url=config.base_url, api_key=config.api_key, timeout=180)

    try:
        response = client.chat.completions.create(
            model=config.model,
            messages=[
                {"role": "system", "content": VARIANT_SYSTEM_PROMPT},
                {"role": "user", "content": f"Frage: {version.ausgangsfrage}"},
            ],
            temperature=0.3,
            max_tokens=JUDGE_MAX_TOKENS,
        )
    except OpenAIError as exc:
        raise JudgeUnavailable(f"{type(exc).__name__}: {exc}") from exc

    content = (response.choices[0].message.content or "").strip()
    if not content:
        raise JudgeUnavailable(
            f"The model returned no content (finish_reason={response.choices[0].finish_reason!r})."
        )

    proposed = parse_variants(content)

    existing = {
        v.stil: v
        for v in session.execute(
            select(Variant).where(Variant.case_version_id == version.id)
        ).scalars()
    }

    out: list[Variant] = []
    for stil in VARIANTEN_STILE:
        current = existing.get(stil)
        if current is not None and current.is_approved:
            # Already read and approved by a person. A regeneration must not
            # quietly replace what a round may already have measured.
            out.append(current)
            continue
        variant = current or Variant(case_version_id=version.id, stil=stil)
        variant.wortlaut = proposed[stil]
        variant.status = VORGESCHLAGEN
        variant.erstellt_durch = ERSTELLT_DURCH_LLM
        session.add(variant)
        out.append(variant)

    session.flush()
    return out


def parse_variants(content: str) -> dict[str, str]:
    """Read the model's JSON, refusing anything incomplete.

    A missing style is not filled in with the original question: that would
    silently turn a robustness check into a fourth repeat, and 4.2 would report
    stability it never tested.
    """
    match = re.search(r"\{.*\}", content, re.S)
    if match is None:
        raise JudgeUnavailable(f"No JSON object in the reply: {content[:200]!r}")
    try:
        parsed = json.loads(match.group(0))
    except json.JSONDecodeError as exc:
        raise JudgeUnavailable(f"The reply's JSON did not parse: {exc}") from exc

    missing = [stil for stil in VARIANTEN_STILE if not str(parsed.get(stil, "")).strip()]
    if missing:
        raise JudgeUnavailable(f"The reply is missing {', '.join(missing)}.")

    return {stil: str(parsed[stil]).strip() for stil in VARIANTEN_STILE}


def approve(session: Session, variant: Variant, *, freigegeben_durch: str) -> Variant:
    """A person has read this and confirmed it asks the same question."""
    if not freigegeben_durch.strip():
        raise VariantError("A variant needs a name against its approval.")
    if variant.is_approved:
        return variant
    variant.status = FREIGEGEBEN
    variant.freigegeben_durch = freigegeben_durch
    variant.freigegeben_at = datetime.now(UTC)
    session.flush()
    return variant


def edit(session: Session, variant: Variant, wortlaut: str) -> Variant:
    """Correct a proposal before approving it.

    A reviewer who can only accept or reject has to reject three good variants
    over one clumsy word. An approved one is frozen.
    """
    if variant.is_approved:
        raise ApprovedVariantIsFrozen(
            f"The {variant.stil} variant is approved. A round may have measured against these "
            f"words, so add a new case version rather than changing them."
        )
    variant.wortlaut = wortlaut
    session.flush()
    return variant


def for_version(session: Session, case_version_id: UUID) -> list[Variant]:
    return list(
        session.execute(
            select(Variant).where(Variant.case_version_id == case_version_id).order_by(Variant.stil)
        ).scalars()
    )


def approved_for(session: Session, case_version_id: UUID) -> list[Variant]:
    """What a run should actually ask. Only approved variants count."""
    return [v for v in for_version(session, case_version_id) if v.is_approved]
